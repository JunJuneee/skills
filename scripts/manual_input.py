# FDR 종목명 → 코드 매핑 캐시
_krx_cache = None
def get_code_by_name(name):
    """종목명으로 코드 조회 (하드코딩 → FDR → '?' 순)"""
    # 1. 하드코딩 딕셔너리 우선
    if name in _KNOWN_CODES:
        return _KNOWN_CODES[name]

    global _krx_cache
    if _krx_cache is None:
        _krx_cache = {}
        try:
            for src in ['KRX', 'ETF/KR']:
                df = fdr.StockListing(src)
                col_code = 'Code' if 'Code' in df.columns else 'Symbol'
                for _, row in df.iterrows():
                    _krx_cache[row['Name']] = row[col_code]
        except Exception as e:
            print(f"  ⚠️ FDR 서버 오류 ({e.__class__.__name__}) — 하드코딩 코드만 사용")

    # 2. FDR 캐시 정확 일치
    if name in _krx_cache:
        return _krx_cache[name]
    # 3. FDR 부분 일치
    for n, c in _krx_cache.items():
        if name in n or n in name:
            return c
    # 4. 하드코딩 부분 일치
    for n, c in _KNOWN_CODES.items():
        if name in n or n in name:
            return c
    return None


def init_db():
    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
    conn = sqlite3.connect(DB_PATH)
    conn.execute('''
        CREATE TABLE IF NOT EXISTS net_purchases (
            date TEXT, market TEXT, investor TEXT,
            ticker TEXT, name TEXT,
            net_value INTEGER, rank INTEGER,
            UNIQUE(date, market, investor, ticker, rank)
        )
    ''')
    conn.commit()
    return conn


def insert_data(conn, date, investor, kind, items):
    """
    items: [(rank, name, value_억), ...]
    kind: 'buy' or 'sell'
    """
    sign = 1 if kind == 'buy' else -1
    for rank, name, value_억 in items:
        code = get_code_by_name(name)
        if code is None:
            print(f"  ⚠️ 코드 없음: {name}")
            code = '?'
        net_value = sign * int(value_억 * 1e8)  # 억 → 원
        try:
            conn.execute('''
                INSERT OR REPLACE INTO net_purchases
                (date, market, investor, ticker, name, net_value, rank)
                VALUES (?, ?, ?, ?, ?, ?, ?)
            ''', (date, 'KOSPI', f'{investor}_{kind}', code, name, net_value, rank))
        except Exception as e:
            print(f"  ERR ({name}): {e}")
    conn.commit()


